#!/usr/bin/env python3
"""Read-only inventory and curated local artifact index. Python 3.10+; stdlib only.

Reads project files and writes only explicitly requested, tool-owned index files.
Never executes a project command, evaluates a result, moves, renames, or deletes it.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import html
import json
import os
from pathlib import Path
import sys
from typing import Any
from urllib.parse import quote

GENERATOR = "engineering-project-memory/catalog-v1"
MD_MARKER = "<!-- Generated by engineering-project-memory/catalog-v1; edit selected.json instead. -->"
HTML_MARKER = "<!-- Generated by engineering-project-memory/catalog-v1. -->"
SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "__pycache__", ".cache"}
DEFAULT_EXTS = ".mp4,.webm,.gif,.png,.jpg,.jpeg,.md,.py,.ipynb,.yaml,.yml,.json,.toml,.usd,.usda,.usdc,.npy,.npz,.h5,.hdf5"


def stamp() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def local_path(root: Path, value: str) -> Path:
    """Accept only workspace-relative paths whose targets stay inside root."""
    if not isinstance(value, str) or not value or Path(value).is_absolute():
        raise ValueError(f"Expected a nonempty workspace-relative path: {value!r}")
    p = (root / value).resolve()
    if not p.is_relative_to(root):
        raise ValueError(f"Path leaves workspace: {value!r}")
    return p


def write_owned(path: Path, text: str, fmt: str) -> None:
    """Refuse to overwrite anything not explicitly marked as this tool's output."""
    if path.exists():
        if not path.is_file():
            raise ValueError(f"Not a regular output file: {path}")
        old = path.read_text(encoding="utf-8")
        if fmt == "json":
            try:
                data = json.loads(old)
                owned = isinstance(data, dict) and data.get("generated_by") == GENERATOR
            except json.JSONDecodeError:
                owned = False
        else:
            marker = MD_MARKER if fmt == "md" else HTML_MARKER
            owned = old.startswith(marker)
        if not owned:
            raise ValueError(f"Refusing to overwrite a non-generated file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    # Direct write: no deletion/renaming of user artifacts or temp files.
    path.write_text(text, encoding="utf-8")


def inventory(root: Path, scans: list[str], out: Path, suffixes: set[str], limit: int) -> dict[str, Any]:
    """Metadata only; no hash/video analysis; intentionally does not follow symlinks."""
    entries: list[dict[str, Any]] = []
    warnings: list[str] = []
    seen: set[str] = set()
    scanned_roots: list[str] = []
    truncated = False
    for raw in scans:
        start = local_path(root, raw)
        if (root / raw).is_symlink():
            warnings.append(f"Skipped explicitly selected symlink directory: {raw}")
            continue
        if not start.is_dir():
            warnings.append(f"Missing or non-directory scan root: {raw}")
            continue
        scanned_roots.append(start.relative_to(root).as_posix())
        def onerror(exc: OSError) -> None:
            warnings.append(str(exc))
        for base, dirs, names in os.walk(start, followlinks=False, onerror=onerror):
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not (Path(base) / d).is_symlink())
            for name in sorted(names):
                p = Path(base) / name
                if p.is_symlink() or p.resolve() == out or (suffixes and p.suffix.lower() not in suffixes):
                    continue
                rel = p.relative_to(root).as_posix()
                if rel in seen:
                    continue
                if len(entries) >= limit:
                    warnings.append(f"Stopped at --max-files={limit}; inventory is partial.")
                    truncated = True
                    break
                try:
                    st = p.stat()
                    if not p.is_file():
                        continue
                    entries.append({"path": rel, "extension": p.suffix.lower(), "size_bytes": st.st_size,
                                    "mtime_utc": datetime.fromtimestamp(st.st_mtime, timezone.utc).isoformat()})
                    seen.add(rel)
                except OSError as exc:
                    warnings.append(f"{rel}: {exc}")
            if truncated:
                break
        if truncated:
            break
    entries.sort(key=lambda row: row["path"])
    return {"schema_version": 1, "generated_by": GENERATOR, "generated_at": stamp(),
            "scope": {"requested_roots": scans, "scanned_roots": scanned_roots,
                      "extensions": sorted(suffixes), "follow_symlinks": False,
                      "excluded_directory_names": sorted(SKIP_DIRS)},
            "complete_within_scope": not warnings, "warnings": warnings,
            "note": "Metadata snapshot only; mtime is not creation time, stage, provenance, or quality evidence.",
            "count": len(entries), "files": entries}


def load_selected(root: Path, source: Path) -> list[dict[str, Any]]:
    raw = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or raw.get("schema_version") != 1 or not isinstance(raw.get("items"), list):
        raise ValueError("Expected selected.json with schema_version=1 and items=[...]")
    if raw.get("template_only"):
        raise ValueError("Example/template selections cannot be published as actual artifacts.")
    seen: set[str] = set()
    items: list[dict[str, Any]] = []
    for n, obj in enumerate(raw["items"], 1):
        if not isinstance(obj, dict):
            raise ValueError(f"Item {n} must be an object.")
        for key in ("id", "stage", "title", "kind", "path", "reason", "scope"):
            if not isinstance(obj.get(key), str) or not obj[key].strip():
                raise ValueError(f"Item {n}: missing nonempty string {key!r}")
        if obj["id"] in seen:
            raise ValueError(f"Duplicate selection id: {obj['id']}")
        seen.add(obj["id"])
        roles = obj.get("roles", [])
        if not isinstance(roles, list) or not all(isinstance(x, str) and x.strip() for x in roles):
            raise ValueError(f"Item {n}: roles must be a list of nonempty strings")
        target = local_path(root, obj["path"])
        if not target.is_file():
            raise ValueError(f"Item {n}: missing artifact file: {obj['path']}")
        manifest = obj.get("manifest")
        if manifest is not None and not local_path(root, manifest).is_file():
            raise ValueError(f"Item {n}: missing manifest file: {manifest}")
        items.append(obj)
    return items


def href(root: Path, output: Path, target: str) -> str:
    return quote(Path(os.path.relpath(local_path(root, target), output.parent)).as_posix(), safe="/._-")


def md_text(value: Any) -> str:
    text = html.escape(str(value), quote=False).replace("\n", " ").replace("\r", " ")
    for ch in "\\|[]`*_":
        text = text.replace(ch, "\\" + ch)
    return text


def render_md(root: Path, source: Path, output: Path, items: list[dict[str, Any]]) -> str:
    source_link = href(root, output, source.relative_to(root).as_posix())
    lines = [MD_MARKER, "# 精选阶段产物", "",
             f"生成于 {stamp()}。选择来源：[精选清单]({source_link})。", "",
             "此页是精选视图，不是全部输出库存；时间先后不代表质量。选择理由由维护者填写，脚本不验证物理行为或实验结论。", ""]
    if not items:
        lines += ["尚未登记精选产物。先核查实际文件和记录，再在清单中添加；不要用示例冒充项目成果。", ""]
    else:
        lines += ["| 阶段 / 标识 | 产物与用途 | 保留理由 | 条件与验证入口 |",
                  "|---|---|---|---|"]
        for x in items:
            link = f"[{md_text(x['title'])}]({href(root, output, x['path'])})"
            roles = ", ".join(x.get("roles", [])) or "未分类用途"
            meta = f"[运行/版本记录]({href(root, output, x['manifest'])})" if x.get("manifest") else "来源/验证记录未关联"
            lines.append(f"| {md_text(x['stage'])} / {md_text(x['id'])} | {link} — {md_text(x['kind'])}; {md_text(roles)} | {md_text(x['reason'])} | {md_text(x['scope'])}; {meta} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def render_html(root: Path, source: Path, output: Path, items: list[dict[str, Any]]) -> str:
    cards: list[str] = []
    for x in items:
        esc = html.escape
        u = href(root, output, x["path"])
        roles = ", ".join(x.get("roles", [])) or "未分类用途"
        meta = (f'<a href="{href(root, output, x["manifest"])}">运行/版本记录</a>'
                if x.get("manifest") else "来源/验证记录未关联")
        search = esc(" ".join(str(x[k]) for k in ("stage", "id", "title", "kind", "reason", "scope")) + " " + roles, quote=True)
        cards.append(f'<article data-search="{search}"><small>{esc(x["stage"])} · {esc(x["id"])}</small>'
                     f'<h2><a href="{u}">{esc(x["title"])}</a></h2><p>{esc(x["kind"])} · {esc(roles)}</p>'
                     f'<p><strong>为何保留：</strong>{esc(x["reason"])}</p><p><strong>条件与范围：</strong>{esc(x["scope"])}</p>'
                     f'<p>{meta}</p></article>')
    body = "\n".join(cards) or "<p>尚未登记精选产物；请先核查实际文件与来源。</p>"
    source_link = href(root, output, source.relative_to(root).as_posix())
    return HTML_MARKER + '''
<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>精选阶段产物</title><style>
body{font-family:system-ui,sans-serif;max-width:960px;margin:40px auto;padding:0 24px;line-height:1.7}
input{box-sizing:border-box;width:100%;padding:12px;font:inherit}article{border:1px solid;padding:20px;margin:18px 0;border-radius:8px}
h2{margin:8px 0}small{font-size:.9em}p{margin:8px 0}[hidden]{display:none!important}
</style><h1>精选阶段产物</h1>''' + f'<p>生成于 {stamp()} · <a href="{source_link}">精选清单</a></p>' + '''
<p>按阶段和用途查找，不以最新代替最好。此页不验证物理行为或实验结论。</p>
<label for="q">搜索阶段、标题、用途或说明</label><input id="q" type="search" placeholder="例如：基线、展示、失败对照" autocomplete="off">
<main>''' + body + '''</main><script>
document.getElementById('q').addEventListener('input',function(){const q=this.value.toLowerCase().trim();document.querySelectorAll('article').forEach(a=>{a.hidden=!a.dataset.search.toLowerCase().includes(q);});});
</script></html>\n'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    inv = sub.add_parser("inventory", help="Read file metadata from explicit directories; do not classify results")
    inv.add_argument("--root", default=".")
    inv.add_argument("--scan", action="append", required=True, help="Workspace-relative directory; repeat as needed")
    inv.add_argument("--out", default="artifacts/inventory.json")
    inv.add_argument("--extensions", default=DEFAULT_EXTS, help="Comma-separated suffixes; empty scans all file types")
    inv.add_argument("--max-files", type=int, default=20000)
    for name in ("build", "check"):
        p = sub.add_parser(name, help="Generate selected indexes" if name == "build" else "Validate selection structure and file paths")
        p.add_argument("--root", default=".")
        p.add_argument("--selected", default="artifacts/selected.json")
        if name == "build":
            p.add_argument("--out", default="docs/ARTIFACTS.md")
            p.add_argument("--html", help="Optional workspace-relative HTML output")
    args = parser.parse_args(argv)
    try:
        root = Path(args.root).expanduser().resolve()
        if not root.is_dir():
            raise ValueError(f"Workspace root is not a directory: {root}")
        if args.command == "inventory":
            if args.max_files <= 0:
                raise ValueError("--max-files must be positive")
            out = local_path(root, args.out)
            exts = {x.strip().lower() for x in args.extensions.split(",") if x.strip()}
            record = inventory(root, args.scan, out, exts, args.max_files)
            write_owned(out, json.dumps(record, ensure_ascii=False, indent=2) + "\n", "json")
            print(f"Saved {record['count']} metadata rows to {out}")
            for warning in record["warnings"]:
                print("WARNING: " + warning, file=sys.stderr)
            return 0 if record["complete_within_scope"] else 2
        source = local_path(root, args.selected)
        items = load_selected(root, source)
        if args.command == "check":
            print(f"OK: {len(items)} selections; local file links exist. No scientific/semantic validation performed.")
            return 0
        out = local_path(root, args.out)
        if out == source:
            raise ValueError("Index output cannot replace selected.json")
        write_owned(out, render_md(root, source, out, items), "md")
        print(f"Built {out}")
        if args.html:
            dest = local_path(root, args.html)
            if dest in (source, out):
                raise ValueError("HTML output must differ from selection and Markdown files")
            write_owned(dest, render_html(root, source, dest, items), "html")
            print(f"Built {dest}")
        return 0
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
